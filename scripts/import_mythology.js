// ====================== 合并工具函数 ======================

// 合并 props：保留已有属性，添加缺失属性
function mergeProps(existing, newData) {
  const merged = { ...(existing || {}) };
  for (const key of Object.keys(newData || {})) {
    if (!(key in merged)) {
      merged[key] = newData[key];
    }
  }
  return merged;
}

// 合并数组：去重合并（保持已有在前）
function mergeArrays(existing, newData) {
  const result = [...(existing || [])];
  for (const item of (newData || [])) {
    if (!result.includes(item)) {
      result.push(item);
    }
  }
  return result;
}

// 合并对象数组（按 target 去重）
function mergeObjArrays(existing, newData) {
  const result = [...(existing || [])];
  const existingTargets = new Set(result.map(o => o.target));
  for (const item of (newData || [])) {
    if (!existingTargets.has(item.target)) {
      result.push(item);
      existingTargets.add(item.target);
    }
  }
  return result;
}

// 合并 relations：保留已有关系，添加缺失的关系
function mergeRelations(existing, newData) {
  const merged = { ...(existing || {}) };
  for (const key of Object.keys(newData || {})) {
    if (!(key in merged) || !merged[key]) {
      merged[key] = newData[key];
    } else {
      // 已有该关系类型，合并数组
      const sample = newData[key][0];
      if (sample && typeof sample === 'object') {
        merged[key] = mergeObjArrays(merged[key], newData[key]);
      } else {
        merged[key] = mergeArrays(merged[key], newData[key]);
      }
    }
  }
  return merged;
}

// 合并 sources：按 id 去重合并
function mergeSources(existing, newData) {
  if (!existing || existing.length === 0) return [...(newData || [])];
  const result = [...existing];
  const existingIds = new Set(result.map(s => s.id));
  for (const item of (newData || [])) {
    if (!existingIds.has(item.id)) {
      result.push(item);
      existingIds.add(item.id);
    }
  }
  return result;
}

// 合并单个实体：保留已有数据，添加缺失数据
function mergeEntity(existing, newData) {
  return {
    ...newData,
    id: existing.id,
    name: existing.name || newData.name,
    type: existing.type || newData.type,
    props: mergeProps(existing.props, newData.props),
    aliases: mergeArrays(existing.aliases, newData.aliases),
    tags: mergeArrays(existing.tags, newData.tags),
    relations: mergeRelations(existing.relations, newData.relations),
    sources: mergeSources(existing.sources, newData.sources),
    // 保留已有的 wikiUrl（不主动添加新的）
    ...(existing.wikiUrl ? { wikiUrl: existing.wikiUrl } : {}),
  };
}

