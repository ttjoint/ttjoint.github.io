function main() {
  console.log('=== 中国古代神话至先秦时代数据导入 ===\n');

  // 1. 读取现有数据
  let existingPersons = [];
  let existingOrgs = [];
  let existingEvents = [];

  if (fs.existsSync(PERSONS_FILE)) {
    existingPersons = JSON.parse(fs.readFileSync(PERSONS_FILE, 'utf-8'));
  }
  if (fs.existsSync(ORGS_FILE)) {
    existingOrgs = JSON.parse(fs.readFileSync(ORGS_FILE, 'utf-8'));
  }
  if (fs.existsSync(EVENTS_FILE)) {
    existingEvents = JSON.parse(fs.readFileSync(EVENTS_FILE, 'utf-8'));
  }

  // 2. 合并组织（以 id 去重，存在则合并，不存在则新增）
  let orgAdded = 0, orgUpdated = 0;
  const orgMap = new Map(existingOrgs.map(o => [o.id, o]));
  for (const org of ORGS) {
    if (orgMap.has(org.id)) {
      orgMap.set(org.id, mergeEntity(orgMap.get(org.id), org));
      orgUpdated++;
    } else {
      orgMap.set(org.id, org);
      orgAdded++;
    }
  }
  const mergedOrgs = [...orgMap.values()];
  console.log(`组织: 原有 ${existingOrgs.length} + 新增 ${orgAdded} + 更新 ${orgUpdated} = 合并 ${mergedOrgs.length}`);

  // 3. 合并人物（以 id 去重，存在则合并，不存在则新增）
  let personAdded = 0, personUpdated = 0;
  const personMap = new Map(existingPersons.map(p => [p.id, p]));
  for (const person of PERSONS) {
    if (personMap.has(person.id)) {
      personMap.set(person.id, mergeEntity(personMap.get(person.id), person));
      personUpdated++;
    } else {
      personMap.set(person.id, person);
      personAdded++;
    }
  }
  const mergedPersons = [...personMap.values()];
  console.log(`人物: 原有 ${existingPersons.length} + 新增 ${personAdded} + 更新 ${personUpdated} = 合并 ${mergedPersons.length}`);

  // 4. 合并事件（以 id 去重，存在则合并，不存在则新增）
  let eventAdded = 0, eventUpdated = 0;
  const eventMap = new Map(existingEvents.map(e => [e.id, e]));
  for (const event of EVENTS) {
    if (eventMap.has(event.id)) {
      eventMap.set(event.id, mergeEntity(eventMap.get(event.id), event));
      eventUpdated++;
    } else {
      eventMap.set(event.id, event);
      eventAdded++;
    }
  }
  const mergedEvents = [...eventMap.values()];
  console.log(`事件: 原有 ${existingEvents.length} + 新增 ${eventAdded} + 更新 ${eventUpdated} = 合并 ${mergedEvents.length}`);

  // 5. 写入文件（2 空格缩进，保留中文）
  fs.writeFileSync(PERSONS_FILE, JSON.stringify(mergedPersons, null, 2), 'utf-8');
  console.log(`\n人物数据已写入: ${PERSONS_FILE}`);

  fs.writeFileSync(ORGS_FILE, JSON.stringify(mergedOrgs, null, 2), 'utf-8');
  console.log(`组织数据已写入: ${ORGS_FILE}`);

  fs.writeFileSync(EVENTS_FILE, JSON.stringify(mergedEvents, null, 2), 'utf-8');
  console.log(`事件数据已写入: ${EVENTS_FILE}`);

  // 6. 统计信息
  console.log('\n=== 导入统计 ===');

  // 按时代分布统计
  const periods = {};
  for (const p of PERSONS) {
    for (const tag of p.tags) {
      if (['神话时代', '夏朝', '商朝', '西周', '古籍记述者'].includes(tag)) {
        periods[tag] = (periods[tag] || 0) + 1;
      }
    }
  }
  console.log('人物按时代分布:', JSON.stringify(periods, null, 2));

  console.log(`\n新增组织 (${orgAdded}): ${ORGS.filter(o => !existingOrgs.find(eo => eo.id === o.id)).map(o => o.id).join('、')}`);
  console.log(`更新组织 (${orgUpdated}): ${ORGS.filter(o => existingOrgs.find(eo => eo.id === o.id)).map(o => o.id).join('、') || '无'}`);

  console.log(`\n新增人物 (${personAdded}): ${PERSONS.filter(p => !existingPersons.find(ep => ep.id === p.id)).map(p => p.id).join('、')}`);
  console.log(`更新人物 (${personUpdated}): ${PERSONS.filter(p => existingPersons.find(ep => ep.id === p.id)).map(p => p.id).join('、') || '无'}`);

  console.log(`\n新增事件 (${eventAdded}): ${EVENTS.filter(e => !existingEvents.find(ee => ee.id === e.id)).map(e => e.id).join('、')}`);
  console.log(`更新事件 (${eventUpdated}): ${EVENTS.filter(e => existingEvents.find(ee => ee.id === e.id)).map(e => e.id).join('、') || '无'}`);

  // 来源链统计
  const sourceStats = { total: 0, byType: {} };
  for (const [type, arr] of [['人物', PERSONS], ['组织', ORGS], ['事件', EVENTS]]) {
    let count = 0;
    for (const item of arr) {
      if (item.sources) count += item.sources.length;
    }
    sourceStats.byType[type] = count;
    sourceStats.total += count;
  }
  console.log(`\n来源链统计: 共 ${sourceStats.total} 条来源记录`);
  console.log(`  人物: ${sourceStats.byType['人物']} 条`);
  console.log(`  组织: ${sourceStats.byType['组织']} 条`);
  console.log(`  事件: ${sourceStats.byType['事件']} 条`);

  console.log('\n=== 导入完成 ===');
}

main();
