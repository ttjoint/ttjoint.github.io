// ---------------------------------------------------------------------------
// Entity ids
//
// These tests used to pin the name-derived scheme (`person:sha256(name)`), which
// turned out to be the root cause of every duplicate-node bug in the corpus:
// namesakes collapsed, counters were appended to names to break ties, and the
// counters then hid which shard an importer should have filled. The scheme is
// gone; ids now name their *origin*.
// ---------------------------------------------------------------------------

test('ids: the same origin key always yields the same id', () => {
  assert.strictEqual(ids.cbdbPersonId(467817), ids.cbdbPersonId(467817));
  assert.strictEqual(ids.cbdbPersonId(467817), 'person:cbdb-467817');
});

test('ids: different types do not collide on the same key', () => {
  const a = ids.entityId('person', 'src-12345');
  const b = ids.entityId('organization', 'src-12345');
  assert.notStrictEqual(a, b);
  assert.ok(a.startsWith('person:'));
  assert.ok(b.startsWith('organization:'));
});

test('ids: keys are not silently normalised', () => {
  // The old constructor stripped and collapsed whitespace so that "习 近平" and
  // "习  近平" would not fork — treating a *name* problem. A key is generated by
  // machine, so a stray space means a bug upstream, not something to paper over.
  assert.throws(() => ids.entityId('person', '  习 近平  '), /alphanumeric/);
  assert.throws(() => ids.entityId('person', 'cbdb 123'), /alphanumeric/);
});

test('ids: empty keys and unknown types are rejected', () => {
  assert.throws(() => ids.entityId('person', ''), /non-empty/);
  assert.throws(() => ids.entityId('person', '   '), /non-empty/);
  assert.throws(() => ids.entityId('concept', 'x'), /unknown type/);
  assert.throws(() => ids.entityId('person', undefined), /non-empty/);
});

test('ids: ids are opaque — the name never appears in them', () => {
  const p = ids.cbdbPersonId(20209);
  assert.ok(!p.includes('習'), 'an id must not leak the display name');
  assert.strictEqual(ids.parseId(p).key, 'cbdb-20209');
});

test('ids: name-derived constructors throw instead of quietly working', () => {
  // Keeping them callable would let new code mint a plausible-looking id that
  // silently collides with every namesake. Throwing forces the caller to answer
  // "where does this entity come from".
  for (const fn of ['personId', 'thingId', 'organizationId', 'eventId', 'evidenceId']) {
    assert.throws(() => ids[fn]('习近平'), /must not be derived from names/, fn);
  }
});

test('ids: source keys classify by origin', () => {
  assert.ok(ids.isCbdbId('person:cbdb-467817'));
  assert.ok(!ids.isCbdbId('person:local-000042'));
  assert.ok(ids.isLocalId('evidence:local-000002'));
  assert.ok(!ids.isLocalId('person:cbdb-1'));
});

test('ids: source_key derives the same key from equivalent URLs', () => {
  const { keyFromUrl } = require('../../src/store/source_key');
  // Trailing slash and tracking parameters must not fork an entity.
  assert.strictEqual(
    keyFromUrl('https://www.gov.cn/x/content_5745000.htm'),
    keyFromUrl('https://www.gov.cn/x/content_5745000.htm?utm_source=a'),
  );
  // A dated path must not collapse every article from that day into one key.
  assert.strictEqual(keyFromUrl('http://www.npc.gov.cn/c2/c30834/202303/t20230312_17900.html'), '17900');
  assert.strictEqual(keyFromUrl('http://www.npc.gov.cn/c2/c30834/202303/t20230312_18001.html'), '18001');
});

