test('batches: stamp is filename-safe on Windows', () => {
  const stamp = batches.batchStamp(new Date('2026-08-01T12:34:56.789Z'));
  assert.strictEqual(stamp, '2026-08-01T12-34-56-789Z');
  assert.ok(!/[:.]/.test(stamp), 'no colons or dots');
});

test('batches: latest resolves by chronological filename order', () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'hm-batches-'));
  try {
    const a = batches.writeBatch('p-', { n: 1 }, dir, new Date('2026-01-01T00:00:00Z'));
    const b = batches.writeBatch('p-', { n: 2 }, dir, new Date('2026-02-01T00:00:00Z'));
    const other = batches.writeBatch('q-', { n: 9 }, dir, new Date('2026-03-01T00:00:00Z'));

    assert.strictEqual(batches.latestBatchPath('p-', dir), b);
    assert.strictEqual(batches.latestBatchPath('q-', dir), other);
    assert.strictEqual(batches.latestBatchPath('missing-', dir), null);
    assert.deepStrictEqual(batches.listBatches('p-', dir), [path.basename(a), path.basename(b)]);
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
});

test('batches: missing batch names the npm script to run', () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'hm-batches-'));
  try {
    assert.throws(
      () => batches.readLatestBatch('cppcc-verified-', 'npm run verify:cppcc', dir),
      /no "cppcc-verified-\*" batch found.*npm run verify:cppcc/,
    );
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
});

test('batches: writeBatch creates the directory and round-trips UTF-8', () => {
  const dir = path.join(fs.mkdtempSync(path.join(os.tmpdir(), 'hm-batches-')), 'nested', 'deep');
  try {
    const file = batches.writeBatch('x-', { name: '习近平', 中文: '值' }, dir);
    const back = JSON.parse(fs.readFileSync(file, 'utf8'));
    assert.strictEqual(back.name, '习近平');
    assert.strictEqual(back['中文'], '值');
  } finally {
    fs.rmSync(path.dirname(path.dirname(dir)), { recursive: true, force: true });
  }
});

