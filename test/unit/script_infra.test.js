test('html: scripts and styles are removed before text extraction', () => {
  const html = '<html><head><style>.a{color:red}</style></head>'
    + '<body><script>var x="习近平";</script><p>正文</p></body></html>';
  const out = http1.cleanHtml(html);
  assert.ok(!out.includes('var x'), 'script body must not leak');
  assert.ok(!out.includes('color:red'), 'style body must not leak');
  assert.strictEqual(out, '正文');
});

test('html: entities decode, including numeric ones', () => {
  assert.strictEqual(http1.cleanHtml('a&nbsp;b&amp;c&lt;d&gt;'), 'a b&c<d>');
  assert.strictEqual(http1.cleanHtml('x&#8212;y'), 'x—y');
  assert.strictEqual(http1.cleanHtml('q&#x2014;r'), 'q—r');
});

test('html: block tags become separators so paragraphs stay apart', () => {
  const out = http1.cleanHtml('<p>第一段</p><p>第二段</p>', { collapse: false });
  assert.deepStrictEqual(out.split('\n').filter(Boolean), ['第一段', '第二段']);
});

test('html: extractLinks resolves relative hrefs and dedupes', () => {
  const html = '<a href="/a/1.html">甲</a><a href="b/2.html">乙</a><a href="/a/1.html">甲重</a>';
  const links = http1.extractLinks(html, 'https://example.gov.cn/dir/');
  assert.strictEqual(links.length, 2);
  assert.strictEqual(links[0].url, 'https://example.gov.cn/a/1.html');
  assert.strictEqual(links[1].url, 'https://example.gov.cn/dir/b/2.html');
  assert.strictEqual(links[0].text, '甲');
});

test('html: extractTitle survives attributes and inner whitespace', () => {
  assert.strictEqual(http1.extractTitle('<TITLE lang="zh">  某  简历 </TITLE>'), '某 简历');
  assert.strictEqual(http1.extractTitle('<html></html>'), '');
});

test('html: fetchText rejects malformed URLs without a network call', async () => {
  await assert.rejects(() => http1.fetchText('not a url'), /invalid URL/);
});
