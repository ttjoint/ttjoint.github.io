'use strict';
/**
 * Entity shape predicates shared by the validator and the test suite.
 *
 * ## Why this module exists
 *
 * `validate_data.js` and `data_integrity.test.js` both need to answer "is this
 * shard damaged or merely sparse?" If each carries its own copy, the two drift:
 * the test keeps passing while the validator was loosened (or the reverse), and
 * a real regression slips through the gap. The rule is stated once here.
 */

/**
 * True when an entity carries no real content beyond its label.
 *
 * Skips `evidence`: an evidence node's payload is carrier/medium/url/documentedAt,
 * not `props`, so "no props and no relations" is normal there and a blanket rule
 * would mark all 111 of them broken and push someone to switch the check off.
 *
 * `summary` deliberately does not count as content: summary is exactly what
 * survived the index→shard round trip that hollowed 5269 shards, so treating it
 * as content would hide precisely the damage this is meant to catch.
 *
 * `tags` is not mentioned because the field no longer exists. A legacy shard may
 * still carry it, and it must not count as content either — otherwise a hollowed
 * shard that kept only its `tags` would pass this check.
 */
function isHollow(entity, type) {
  if (!entity || type === 'evidence') return false;
  const empty = (v) => !v || (typeof v === 'object' && !Array.isArray(v) && Object.keys(v).length === 0);
  if (!empty(entity.props)) return false;
  if (!empty(entity.relations)) return false;
  if (!empty(entity.claims)) return false;
  return true;
}

/**
 * Hard proof that a shard was written from an index row.
 *
 * This is the only shape that can be attributed to the round trip with certainty:
 * `detail` is generated by `build_index.js` and has no meaning in a shard. Any
 * other "empty" entity might simply have been entered with nothing but a name, and
 * calling that damage would be a guess.
 */
function wasWrittenFromIndex(entity) {
  return !!entity && Object.prototype.hasOwnProperty.call(entity, 'detail');
}

/**
 * Hard proof that a shard was written from an index row.
 *
 * This is the only shape that can be attributed to the round trip with certainty:
 * `detail` is generated by `build_index.js` and has no meaning in a shard. Any
 * other empty entity might simply have been entered with nothing but a name, and
 * calling that damage would be a guess.
 */
function wasWrittenFromIndex(entity) {
  return !!entity && Object.prototype.hasOwnProperty.call(entity, 'detail');
}

/**
 * Provably damaged: hollow AND carrying the index-row fingerprint.
 *
 * The first version of this rule treated every hollow entity as damaged and
 * exempted anything with aliases. That was wrong in both directions: 257 entries
 * holding only a name and a dynasty tag have no aliases and are not damage, while
 * an entity could be given aliases by hand and still have been emptied. The
 * evidence, not the fill level, is what decides.
 */
function isDamaged(entity, type) {
  return isHollow(entity, type) && wasWrittenFromIndex(entity);
}

/** Hollow with no proof of the round trip: a data gap to fill, not a bug. */
function isSkeleton(entity, type) {
  return isHollow(entity, type) && !wasWrittenFromIndex(entity);
}

module.exports = { isHollow, isSkeleton, isDamaged, wasWrittenFromIndex };
